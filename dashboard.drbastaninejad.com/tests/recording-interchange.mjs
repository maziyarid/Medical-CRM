import { spawnSync } from 'node:child_process';
const testsDir = path.dirname(fileURLToPath(import.meta.url));
const frontend = process.env.DRB_RECORDING_FRONTEND_ROOT || path.resolve(testsDir, '../../app.drbastaninejad.com/Frontend');
for (const [name, expected] of Object.entries({
  'session.js': 'f811fbd92c1be802b5d0a943922ecb7320c4e811',
  'chunks.js': '0a7718a2de0297e04b11e7d4896837ffd2ae9ee5'
})) {
  const bytes = fs.readFileSync(path.join(frontend, 'assets/js/recording', name));
  const hash = createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');
  assert.equal(hash, expected, `${name} must match the reviewed PR35 baseline for this interchange check`);
}
const { createSession, transition, assertConsent, createDraft } = await import(pathToFileURL(path.join(frontend, 'assets/js/recording/session.js')).href);
const { buildManifest, validateChunkReceipt, createTranscriptionJob } = await import(pathToFileURL(path.join(frontend, 'assets/js/recording/chunks.js')).href);
const run = spawnSync(process.execPath, [path.join(testsDir, 'run-recording-contracts.mjs'), '--interchange'], { encoding: 'utf8', env: process.env });
assert.equal(run.status, 0, run.stderr || run.stdout);
const fixture = JSON.parse(run.stdout);
const { scope, consent, receipts, job, draft } = fixture;
const sessionId = job.sessionId;
for (const receipt of receipts) {
  const { stored, ...metadata } = receipt;
  assert.equal(stored, true);
  assert.deepEqual(validateChunkReceipt(metadata, receipt), receipt);
  assert.equal('privateObjectId' in receipt, false);
}
console.log('PASS PHP durable receipt matches frontend eleven-field acknowledgement contract');
const manifest = buildManifest({ patientId: scope.patientId, sessionId, chunks: receipts, expectedChunks: 2, audioDurationMs: 60_000 });
